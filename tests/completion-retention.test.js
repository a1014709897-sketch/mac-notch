const test = require("node:test");
const assert = require("node:assert/strict");
const {TaskState} = require("../src/main/state");
const row = (state, extra={}) => ({provider:"codex",id:"a",state,...extra});
test('single completion persists beyond eight seconds and a day until visiting', () => {
  const s = new TaskState();
  s.update([row('running')], 1000);
  s.update([row('ended')], 2000);
  s.expireCompletionBadges(10000);
  s.update([], 90000000);
  assert.equal(s.snapshot()[1].state, 'ended');
  assert.equal(s.completed().length, 1);
  s.acknowledge('codex', 'a');
  assert.equal(s.snapshot()[1].state, 'idle');
  s.update([row('ended')], 90001000);
  assert.equal(s.snapshot()[1].state, 'idle');
});
test('completion yields after eight seconds to remaining work without losing 1/2', () => {
  const s = new TaskState();
  const b = row('running', {id:'b'});
  s.update([row('running'), b], 1000);
  s.update([row('ended'), b], 2000);
  s.expireCompletionBadges(9999);
  assert.equal(s.snapshot()[1].state, 'ended');
  s.expireCompletionBadges(10000);
  assert.equal(s.snapshot()[1].state, 'running');
  assert.deepEqual(s.snapshot()[1].progress, {done:1,total:2});
  assert.equal(s.completed().length, 1);
  s.update([row('ended'), b], 12000);
  assert.equal(s.snapshot()[1].state, 'running');
  s.update([row('ended'), {...b,state:'ended'}], 13000);
  s.expireCompletionBadges(30000);
  assert.equal(s.snapshot()[1].state, 'ended');
  assert.deepEqual(s.snapshot()[1].progress, {done:2,total:2});
});
test('late new task joins unread completion, while other tools cannot expire it', () => {
  const s = new TaskState();
  s.update([row('running')], 1000);
  s.update([row('ended'), row('running',{provider:'claude'})], 2000);
  s.expireCompletionBadges(11000);
  assert.equal(s.snapshot()[1].state, 'ended');
  s.update([row('running',{id:'b'})], 12000);
  s.expireCompletionBadges(12000);
  assert.equal(s.snapshot()[1].state, 'running');
  assert.deepEqual(s.snapshot()[1].progress, {done:1,total:2});
});
test('notification protects temporary completion; help keeps priority and is never acknowledged', () => {
  const s = new TaskState();
  const b = row('running',{id:'b'});
  s.update([row('running'), b], 1000);
  s.update([row('ended'), b], 2000);
  s.expireCompletionBadges(12000, [{provider:'codex',sessionId:'a'}]);
  assert.equal(s.snapshot()[1].state, 'ended');
  s.expireCompletionBadges(13000);
  assert.equal(s.snapshot()[1].state, 'running');
  assert.equal(s.completed().length, 1);
  s.update([row('ended'), {...b,state:'waiting'}], 14000);
  assert.equal(s.snapshot()[1].state, 'waiting');
  assert.equal(s.sessions.get('codex:b').acknowledged, false);
});
